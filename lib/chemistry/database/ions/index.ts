export function getIonByFormula(formula: string): IonRecord | undefined {
  const q = formula.replace(/\s/g, "").toLowerCase()
  return ALL_IONS.find(
    (i) =>
      i.formula.replace(/\s/g, "").toLowerCase() === q ||
      i.aliases.some((a) => a.replace(/\s/g, "").toLowerCase() === q),
  )
}
