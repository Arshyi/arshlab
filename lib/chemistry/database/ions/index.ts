const boards = ["high-school", "ib-sl", "ib-hl", "ap", "a-level", "university-intro"] as const

function ion(
  partial: Omit<IonRecord, "kind" | "examBoards" | "topics" | "subtopics" | "tags"> &
    Partial<Pick<IonRecord, "topics" | "subtopics" | "tags">>,
): IonRecord {
  return {
    kind: "ion",
    examBoards: [...boards],
    topics: partial.topics ?? ["ions"],
    subtopics: partial.subtopics ?? [],
    tags: partial.tags ?? [partial.type],
    ...partial,
  }
}

