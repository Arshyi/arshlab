import type { ScannerBenchmarkFixture } from "./scanner-benchmark-types"

function fixtureInput({
  id,
  name,
  formula,
  functionalGroupHint,
  difficulty,
  ocrQuality,
}: {
  id: string
  name: string
  formula: string
  functionalGroupHint: string
  difficulty: ScannerBenchmarkFixture["difficulty"]
  ocrQuality?: number
}) {
  const difficultyText = difficulty === "clean" ? "clean synthetic" : difficulty
  return {
    moleculeName: name,
    formula,
    condensedFormula: formula,
    functionalGroupHint,
    fileName: `${id}-${difficulty}.png`,
    ocrCompoundIds: [id],
    ocrFormulaCompoundIds: [id],
    ocrNameCompoundIds: [id],
    ocrText: `${name} ${formula} ${functionalGroupHint} ${difficultyText}`,
    ocrQuality: ocrQuality ?? 88,
    ocrChemistryConfidence: ocrQuality ?? 88,
  }
}

